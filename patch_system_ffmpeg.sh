#!/bin/bash

# Script to patch WebRTC to use system FFmpeg instead of bundled FFmpeg
# Based on instructions in NO_FFMPEG.md

set -e

echo "Patching WebRTC to use system FFmpeg..."

# Function to check if a line exists in a file
line_exists() {
    grep -Fq "$1" "$2" 2>/dev/null
}

# 1. First, ensure use_system_ffmpeg is defined in ffmpeg_options.gni
echo "Updating src/third_party/ffmpeg/ffmpeg_options.gni..."
if ! line_exists "use_system_ffmpeg" "src/third_party/ffmpeg/ffmpeg_options.gni"; then
    # Add use_system_ffmpeg to the declare_args block
    sed -i '/declare_args() {/a\  # Use system FFmpeg instead of bundled\n  use_system_ffmpeg = false' src/third_party/ffmpeg/ffmpeg_options.gni
fi

# 2. Create minimal ffmpeg_generated_system.gni for system builds
echo "Creating src/third_party/ffmpeg/ffmpeg_generated_system.gni..."
cat > src/third_party/ffmpeg/ffmpeg_generated_system.gni << 'EOF'
# Minimal generated file for system FFmpeg
ffmpeg_c_sources = []
ffmpeg_gas_sources = []
ffmpeg_asm_sources = []
ffmpeg_nasm_sources = []
ffmpeg_yasm_sources = []
EOF

# 3. Create a completely new BUILD.gn file for system FFmpeg
echo "Creating new src/third_party/ffmpeg/BUILD.gn..."
cp src/third_party/ffmpeg/BUILD.gn src/third_party/ffmpeg/BUILD.gn.backup 2>/dev/null || true

cat > src/third_party/ffmpeg/BUILD.gn << 'EOF'
# Copyright 2014 The Chromium Authors. All rights reserved.
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

import("ffmpeg_options.gni")

if (use_system_ffmpeg) {
  import("ffmpeg_generated_system.gni")
} else {
  import("ffmpeg_generated.gni")
}

import("//build/buildflag_header.gni")
import("//build/config/compiler/compiler.gni")
import("//build/config/sanitizers/sanitizers.gni")

if (is_linux && use_system_ffmpeg) {
  import("//build/config/linux/pkg_config.gni")
}

# Path to platform configuration files.
platform_config_root =
    "chromium/config/$ffmpeg_branding/$os_config/$ffmpeg_arch"

has_nasm_deps =
    ffmpeg_asm_sources != [] &&
    (current_cpu == "x86" || current_cpu == "x64") && os_config != "linux-noasm"

if (has_nasm_deps && !use_system_ffmpeg) {
  import("//third_party/nasm/nasm_assemble.gni")

  # x86inc.asm ignores the PIC flag when compiling for x86 which unfortunately
  # causes text relocations in the object files generated by the assembler. We
  # must disable the warning to allow linking with lld. Unlike gold, ld which
  # will silently allow text relocations, lld support must be explicit.
  #
  # See https://crbug.com/911658#c19 for more information. Tracked upstream at
  # https://trac.ffmpeg.org/ticket/7878
  config("fix_textrels") {
    ldflags = [ "-Wl,-z,notext" ]
  }

  nasm_assemble("ffmpeg_nasm") {
    sources = ffmpeg_asm_sources

    # Ensure the architecture defines go in the command line before the -P
    # file below, so don't use defines.
    nasm_flags = []
    if (current_cpu == "x86") {
      nasm_flags += [ "-DARCH_X86_32" ]
    } else if (current_cpu == "x64") {
      nasm_flags += [ "-DARCH_X86_64" ]
    }

    inputs = [
      # Sets visibility hidden for cglobal functions. Explicitly included
      # to avoid overlooking changes to this file in incremental builds.
      "libavutil/x86/x86inc.asm",
    ]

    defines = [ "PIC" ]
    include_dirs = [
      platform_config_root,
      "libavcodec/x86",
      "libavutil/x86",
      ".",
    ]

    nasm_flags += [
      "-W+error=all",
      "-Wno-macro-params-legacy",
      "-P" + rebase_path("$platform_config_root/config.asm", root_build_dir),
    ]

    if (is_apple) {
      # Necessary to ensure symbols end up with a _ prefix; added by
      # yasm_assemble.gni for Windows, but not for Apple.
      defines += [ "PREFIX" ]
    }

    # See comments on fix_textrels config.
    if (use_lld && current_cpu == "x86" && !is_win) {
      all_dependent_configs = [ ":fix_textrels" ]
    }
  }
} else {
  # Empty target when not using bundled FFmpeg or no nasm deps
  static_library("ffmpeg_nasm") {
    sources = []
  }
}

config("ffmpeg_dependent_config") {
  include_dirs = [
    platform_config_root,
    ".",
  ]
}

if (is_win) {
  # Stub generator script and signatures of all functions used by Chrome.
  generate_stubs_script = "//tools/generate_stubs/generate_stubs.py"

  # Used by ffmpeg_generate_stubs and ffmpeg_generate_def
  sig_files = [ "chromium/ffmpeg.sigs" ]

  action("ffmpeg_generate_def") {
    script = generate_stubs_script
    sources = sig_files
    outputs = [ "$target_gen_dir/ffmpeg.def" ]
    args = [
             "-i",
             rebase_path(target_out_dir, root_build_dir),
             "-o",
             rebase_path(target_gen_dir, root_build_dir),
             "-t",
             "windows_def",
             "-m",
             "ffmpeg.dll",
           ] + rebase_path(sources, root_build_dir)
  }
}

# gn orders flags on a target before flags from configs. The default config
# adds -Wall, and these flags have to be after -Wall -- so they need to come
# from a config and can't be on the target directly.
config("ffmpeg_warnings") {
  if (is_clang) {
    cflags = [
      "-Wno-absolute-value",

      # ffmpeg uses its own deprecated functions.
      "-Wno-deprecated-declarations",

      # ffmpeg doesn't care about pointer constness.
      "-Wno-incompatible-pointer-types",

      # ffmpeg doesn't follow usual parentheses conventions.
      "-Wno-logical-op-parentheses",

      # ffmpeg doesn't care about pointer signedness.
      "-Wno-parentheses",

      # ffmpeg doesn't care about pointer signedness.
      "-Wno-pointer-sign",

      # ffmpeg doesn't believe in exhaustive switch statements.
      "-Wno-switch",

      # matroskadec.c has a "failed:" label that's only used if some
      # CONFIG_ flags we don't set are set.
      "-Wno-unused-label",

      # ffmpeg has a lot of unused variables.
      "-Wno-unused-variable",

      # This fires on `av_assert0(!"valid element size")` in utils.c
      "-Wno-string-conversion",

      # This fires on `pos_min` and `pos_max` in
      # autorename_libavformat_utils.c
      "-Wno-sometimes-uninitialized",

      # clock_gettime is marked as 10.12+ in the 10.12 SDK, but ffmpeg does
      # correctly check for that before calling.
      "-Wno-unguarded-availability",

      # ffmpeg contains static functions in header files, which lead
      # to unused function warnings. There are a few legit unused
      # functions too.
      "-Wno-unused-function",

      # vp3data.h's vp31_inter_dequant stores '128' in an int8_t array.
      "-Wno-constant-conversion",

      # utils.c does
      # `return LICENSE_PREFIX FFMPEG_LICENSE + sizeof(LICENSE_PREFIX) - 1;`
      # while -Wstring-plus-int wants &FFMPEG_LICENSE[sizeof(LICENSE_PREFIX)-1]
      "-Wno-string-plus-int",

      # video_enc_params.c has a condition that is always false when size_t is
      # 64 bits.
      "-Wno-tautological-constant-out-of-range-compare",

      # Various files convert MAX_INT to double and similar without casting.
      "-Wno-implicit-int-float-conversion",
    ]

    if (target_cpu == "arm" || target_cpu == "arm64") {
      # ffmpeg uses ARM instructions that clang deems deprecated.
      cflags += [ "-Wno-inline-asm" ]
    }

    if (is_win) {
      # This corresponds to /wd4273 below.
      cflags += [ "-Wno-inconsistent-dllimport" ]
    }
  }
}

buildflag_header("ffmpeg_features") {
  header = "ffmpeg_features.h"
  flags = [ "USE_SYSTEM_FFMPEG=$use_system_ffmpeg" ]
}

if (use_system_ffmpeg) {
  # System FFmpeg configuration
  if (is_linux) {
    config("system_ffmpeg") {
      # When using sysroot, we need to manually specify the system FFmpeg paths
      # because pkg-config would look in the sysroot instead of the host system.
      # These are the standard locations for FFmpeg on most Linux distributions.
      # For other architectures, adjust the paths accordingly:
      # - ARM64: /usr/lib/aarch64-linux-gnu
      # - ARM32: /usr/lib/arm-linux-gnueabihf
      cflags = [
        "-isystem/usr/include/x86_64-linux-gnu",
        "-isystem/usr/include",
      ]
      
      libs = [
        "avcodec",
        "avformat",
        "avutil",
      ]
      
      lib_dirs = [
        "/usr/lib/x86_64-linux-gnu",
        "/usr/lib",
      ]
    }
  } else if (is_mac) {
    config("system_ffmpeg") {
      # macOS system FFmpeg paths
      # Homebrew on Apple Silicon: /opt/homebrew
      # Homebrew on Intel: /usr/local
      # MacPorts: /opt/local
      if (target_cpu == "arm64") {
        # Apple Silicon paths
        cflags = [
          "-isystem/opt/homebrew/include",
          "-isystem/usr/local/include",
          "-isystem/opt/local/include",
        ]
        lib_dirs = [
          "/opt/homebrew/lib",
          "/usr/local/lib",
          "/opt/local/lib",
        ]
      } else {
        # Intel Mac paths
        cflags = [
          "-isystem/usr/local/include",
          "-isystem/opt/homebrew/include",
          "-isystem/opt/local/include",
        ]
        lib_dirs = [
          "/usr/local/lib",
          "/opt/homebrew/lib",
          "/opt/local/lib",
        ]
      }
      
      libs = [
        "avcodec",
        "avformat",
        "avutil",
      ]
    }
  }

  # Simple group target for system FFmpeg
  group("ffmpeg_internal") {
    if (is_linux || is_mac) {
      public_configs = [ ":system_ffmpeg" ]
    } else {
      # Fallback to error for non-Linux/macOS platforms
      assert(false, "System FFmpeg only supported on Linux and macOS")
    }
  }

  # Main ffmpeg target
  group("ffmpeg") {
    public_configs = [ ":ffmpeg_dependent_config" ]
    deps = [ ":ffmpeg_internal" ]
  }

} else {
  # Original bundled FFmpeg build configuration
  if (is_component_ffmpeg) {
    link_target_type = "source_set"
  } else {
    # This must be a static_library in non-component builds to avoid pulling
    # in many large global arrays (and associated code) into chrome.dll.
    link_target_type = "static_library"
  }
  
  target(link_target_type, "ffmpeg_internal") {
    sources = ffmpeg_c_sources + ffmpeg_gas_sources + [
                "$platform_config_root/config.h",
                "$platform_config_root/libavutil/avconfig.h",
              ]
    include_dirs = [
      platform_config_root,
      ".",
    ]
    defines = [
      "HAVE_AV_CONFIG_H",
      "_POSIX_C_SOURCE=200112",
      "_XOPEN_SOURCE=600",
      "PIC",
      "FFMPEG_CONFIGURATION=NULL",
    ]

    if (is_component_ffmpeg) {
      configs += [ "//build/config/sanitizers:cfi_icall_disable" ]
    }

    # Disable internal ffmpeg logs in the official build; this saves ~158kb.
    if (is_official_build) {
      defines += [ "CHROMIUM_NO_LOGGING" ]
    }

    # So we can append below and assume they're defined.
    cflags = []
    ldflags = []
    libs = []
    deps = [
      ":ffmpeg_features",
      "//third_party/opus",
    ]

    configs -= [ "//build/config/compiler:chromium_code" ]
    configs += [
      "//build/config/compiler:no_chromium_code",

      # These must be after no_chromium_code for warning flags to be ordered
      # correctly.
      "//build/config/compiler:no_incompatible_pointer_warnings",
      ":ffmpeg_warnings",
    ]

    # Since we are not often debugging FFmpeg, and performance is
    # unacceptable without optimization, freeze the optimizations to -O2.
    # If someone really wants -O1 , they can change these in their checkout.
    # If you want -O0, see the Gotchas in README.Chromium for why that
    # won't work.
    #
    # In addition to the above reasons, /Od optimization won't remove symbols
    # that are under "if (0)" style sections.  Which lead to link time errors
    # when for example it tries to link an ARM symbol on X86.
    configs -= [ "//build/config/compiler:default_optimization" ]
    configs += [ "//build/config/compiler:optimize_max" ]

    if (ffmpeg_use_unsafe_atomics) {
      if (is_posix || is_fuchsia) {
        include_dirs += [ "compat/atomics/gcc" ]
      } else if (is_win) {
        include_dirs += [ "compat/atomics/win32" ]
      }
    }

    # On x86, sanitizers will fail to compiler the H264 CABAC code due to
    # insufficient registers unless we disable EBP usage. https://crbug.com/786760
    #
    # Windows builds can't compile without EBP because we can't omit frame
    # pointers like we do on posix.
    if (current_cpu == "x86") {
      if (using_sanitizer || is_win || use_lld) {
        defines += [ "HAVE_EBP_AVAILABLE=0" ]
      } else {
        defines += [ "HAVE_EBP_AVAILABLE=1" ]
      }

      # Despite the name, this isn't fixing any bugs with the linker. It's just
      # preventing ffmpeg from silently emitting text relocations. See discussion
      # https://crbug.com/911658#c19 and https://trac.ffmpeg.org/ticket/7878
      if (use_lld && !is_win) {
        defines += [ "BROKEN_RELOCATIONS=1" ]
      }
    }

    if (is_fuchsia || is_posix) {
      cflags += [
        "-fPIC",

        # ffmpeg uses its own deprecated functions.
        "-Wno-deprecated-declarations",
      ]

      # Remove default stack frames config so we can force -fomit-frame-pointer.
      configs -= [ "//build/config/compiler:default_stack_frames" ]

      cflags += [ "-fomit-frame-pointer" ]

      if (!is_clang) {
        # gcc doesn't have flags for specific warnings, so disable them
        # all.
        cflags += [ "-w" ]
      }

      if (current_cpu == "arm" || current_cpu == "arm64") {
        asmflags = []
        if (arm_float_abi == "hard") {
          asmflags += [ "-DHAVE_VFP_ARGS=1" ]
        } else {
          asmflags += [ "-DHAVE_VFP_ARGS=0" ]
        }
      }
    }

    if (is_fuchsia || (is_posix && !is_mac)) {
      defines += [
        "_ISOC99_SOURCE",
        "_LARGEFILE_SOURCE",
      ]
      cflags += [
        "-std=c99",
        "-pthread",
        "-fno-math-errno",
        "-fno-signed-zeros",
        "-fno-tree-vectorize",
      ]
      ldflags = [
        "-L",
        rebase_path(target_gen_dir, root_build_dir),
      ]
      if (!is_android && !is_fuchsia) {
        # OS=android requires that both -lz and -lm occur after
        # -lc++_shared on the link command line. Android link rules
        # already include -lm, and we get -lz as a transitive dependency
        # of libandroid.so, so simply moving both to the non-Android
        # section solves the problem.
        #
        # The root cause of this problem is certain system libraries
        # (libm starting with MNC and libz before MNC, among others)
        # re-export the libgcc unwinder, and libc++ exports the
        # libc++abi unwinder. As we build against libc++ headers, libc++
        # must be the first in the runtime symbol lookup order (among
        # all unwinder-providing libraries).

        # librt for clock_gettime on precise
        libs += [
          "m",
          "z",
          "rt",
        ]
      }
      if (is_component_ffmpeg) {
        # Export all symbols when building as component.
        configs -= [ "//build/config/gcc:symbol_visibility_hidden" ]
        configs += [ "//build/config/gcc:symbol_visibility_default" ]
      }
    }
    if (is_apple) {
      if (is_component_ffmpeg) {
        # Export all symbols when building as component.
        configs -= [ "//build/config/gcc:symbol_visibility_hidden" ]
        configs += [ "//build/config/gcc:symbol_visibility_default" ]
      }

      defines += [ "_DARWIN_C_SOURCE" ]
      if (is_ios) {
        libs -= [ "rt" ]
      }
    } else if (is_win) {
      defines += [
        "_ISOC99_SOURCE",
        "_LARGEFILE_SOURCE",
        "HAVE_AV_CONFIG_H",
      ]

      if (is_component_ffmpeg) {
        # Required to avoid 4049 and 4217 errors around redundant imports.
        cflags += [
          "/FIcompat/msvcrt/snprintf.h",
          "/FIcompat/msvcrt/strtod.h",
        ]
      }

      # TODO(dalecurtis): We should fix these.  http://crbug.com/154421
      cflags += [
        "/wd4996",  # 'function': was declared deprecated
        "/wd4018",  # 'expression': signed/unsigned mismatch
        "/wd4090",  # 'operation' : different 'modifier' qualifiers
        "/wd4305",  # 'identifier': truncation from 'type1' to 'type2'
        "/wd4133",  # 'type' : incompatible types - from 'type1' to 'type2'
        "/wd4146",  # unary minus operator applied to unsigned type, result
                    #   still unsigned

        "/wd4554",  # 'operator' : check operator precedence for possible
                    #   error; use parentheses to clarify precedence

        "/wd4028",  # formal parameter 'number' different from declaration
        "/wd4334",  # 'operator' : result of 32-bit shift implicitly
                    #   converted to 64 bits (was 64-bit shift intended?)

        "/wd4101",  # 'identifier' : unreferenced local variable
        "/wd4102",  # 'label' : unreferenced label
        "/wd4116",  # unnamed type definition in parentheses
        "/wd4307",  # 'operator' : integral constant overflow
        "/wd4273",  # 'function' : inconsistent DLL linkage
        "/wd4005",  # 'identifier' : macro redefinition
        "/wd4056",  # overflow in floating point constant arithmetic
        "/wd4756",  # overflow in constant arithmetic
      ]
      if (current_cpu == "x64") {
        # TODO(wolenetz): We should fix this.  http://crbug.com/171009
        cflags += [ "/wd4267" ]  # Conversion from size_t to 'type'.
      }
    }

    if (has_nasm_deps) {
      deps += [ ":ffmpeg_nasm" ]
    }
  }

  if (is_component_ffmpeg) {
    shared_library("ffmpeg") {
      if (is_android) {
        configs -= [ "//build/config/android:hide_all_but_jni_onload" ]
      }
      public_configs = [ ":ffmpeg_dependent_config" ]
      deps = [ ":ffmpeg_internal" ]

      # So we can append below and assume they're defined.
      ldflags = []

      if (is_fuchsia || (is_posix && !is_mac)) {
        # Fixes warnings PIC relocation when building as component.
        ldflags += [
          "-Wl,-Bsymbolic",
          "-L",
          rebase_path(target_gen_dir, root_build_dir),
        ]
      } else if (is_win) {
        # Windows component build needs the .def file to export ffmpeg symbols.
        deps += [ ":ffmpeg_generate_def" ]
        sources = [ "$target_gen_dir/ffmpeg.def" ]
      }

      if (!is_component_build) {
        if (is_mac) {
          ldflags += [ "-Wl,-install_name,@rpath/libffmpeg.dylib" ]
        } else if (is_linux) {
          all_dependent_configs =
              [ "//build/config/gcc:rpath_for_built_shared_libraries" ]
        }
      }
    }
  } else {
    source_set("ffmpeg") {
      public_configs = [ ":ffmpeg_dependent_config" ]
      deps = [ ":ffmpeg_internal" ]
    }
  }
}
EOF

# 4. Modify Build Scripts
echo "Patching build scripts..."

# Linux Build Script
if [ -f build_linux.sh ]; then
    echo "Patching build_linux.sh..."
    # Replace ffmpeg_branding line with use_system_ffmpeg
    sed -i 's/ffmpeg_branding=\\"Chrome\\" \\/use_system_ffmpeg=true \\/' build_linux.sh
    # Remove rtc_use_ffmpeg_h264_encoder line if it exists
    sed -i '/rtc_use_ffmpeg_h264_encoder=true \\/d' build_linux.sh
fi

# macOS Build Script
if [ -f build_macos.sh ]; then
    echo "Patching build_macos.sh..."
    # Add use_system_ffmpeg=true after rtc_use_h264=true
    if ! grep -q "use_system_ffmpeg=true" build_macos.sh; then
        if [[ "$OSTYPE" == "darwin"* ]]; then
            # macOS sed syntax
            sed -i '' '/rtc_use_h264=true \\/a\
  use_system_ffmpeg=true \\' build_macos.sh
        else
            # Linux sed syntax (when running patch on Linux for macOS build)
            sed -i '/rtc_use_h264=true \\/a\  use_system_ffmpeg=true \\' build_macos.sh
        fi
    fi
fi

# 5. Update H264 Decoder Implementation
echo "Patching H264 decoder implementation..."
H264_DECODER="src/modules/video_coding/codecs/h264/h264_decoder_impl.cc"
if [ -f "$H264_DECODER" ]; then
    # Create a backup
    cp "$H264_DECODER" "$H264_DECODER.backup" 2>/dev/null || true
    
    # Check if we already have the conditional includes
    if ! grep -q "USE_SYSTEM_FFMPEG" "$H264_DECODER"; then
        # Find the line with the first FFmpeg include and get its line number
        LINE_NUM=$(grep -n "third_party/ffmpeg" "$H264_DECODER" | head -1 | cut -d: -f1)
        
        if [ ! -z "$LINE_NUM" ]; then
            # Find the start of the extern "C" block before this line
            EXTERN_C_LINE=$(head -n $((LINE_NUM-1)) "$H264_DECODER" | grep -n "extern \"C\"" | tail -1 | cut -d: -f1)
            
            # Create the replacement content
            cat > /tmp/h264_ffmpeg_includes.txt << 'EOF'
#if defined(USE_SYSTEM_FFMPEG)
// System FFmpeg headers
extern "C" {
#include <libavcodec/avcodec.h>
#include <libavformat/avformat.h>
#include <libavutil/imgutils.h>
#include <libavutil/log.h>
}
#else
// Bundled FFmpeg headers
extern "C" {
#include "third_party/ffmpeg/libavcodec/avcodec.h"
#include "third_party/ffmpeg/libavformat/avformat.h"
#include "third_party/ffmpeg/libavutil/imgutils.h"
#include "third_party/ffmpeg/libavutil/log.h"
}
#endif

EOF
            
            # Find the closing brace of the extern "C" block
            END_LINE=$(tail -n +$LINE_NUM "$H264_DECODER" | grep -n "^}" | head -1 | cut -d: -f1)
            END_LINE=$((LINE_NUM + END_LINE - 1))
            
            # Replace the extern "C" block
            sed -i "${EXTERN_C_LINE},${END_LINE}d" "$H264_DECODER"
            sed -i "$((EXTERN_C_LINE-1))r /tmp/h264_ffmpeg_includes.txt" "$H264_DECODER"
            
            rm -f /tmp/h264_ffmpeg_includes.txt
        fi
    fi
fi

# 6. Add USE_SYSTEM_FFMPEG define when using system FFmpeg
echo "Updating WebRTC Video Coding BUILD.gn..."
VIDEO_CODING_BUILD="src/modules/video_coding/BUILD.gn"
if [ -f "$VIDEO_CODING_BUILD" ]; then
    # First add the ffmpeg_options.gni import if not present
    if ! grep -q "ffmpeg_options.gni" "$VIDEO_CODING_BUILD"; then
        sed -i '/import("\/\/third_party\/libaom\/options.gni")/a\import("//third_party/ffmpeg/ffmpeg_options.gni")' "$VIDEO_CODING_BUILD"
    fi
    
    # Find where ffmpeg is referenced and add the define
    if ! grep -q "USE_SYSTEM_FFMPEG" "$VIDEO_CODING_BUILD"; then
        # Look for the rtc_use_h264 block and add the define
        # This is more robust than trying to match the exact deps line
        sed -i '/if (rtc_use_h264) {/,/^  }$/ {
            /deps += \[/{
                :a
                n
                /]$/{
                    a\    if (use_system_ffmpeg) {\
      defines += [ "USE_SYSTEM_FFMPEG" ]\
    }
                    b
                }
                ba
            }
        }' "$VIDEO_CODING_BUILD"
    fi
fi

echo "Patching complete!"
echo ""
echo "Next steps:"
echo "1. Ensure system FFmpeg is installed:"
echo "   Linux:"
echo "     Ubuntu/Debian: sudo apt-get install libavcodec-dev libavformat-dev libavutil-dev"
echo "     Fedora/RHEL: sudo dnf install ffmpeg-devel"
echo "   macOS:"
echo "     Homebrew: brew install ffmpeg"
